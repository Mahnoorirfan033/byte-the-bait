def clean_urdu_text(text: str):
    # 1. Remove URLs (common in descriptions)
    text = re.sub(r'http\S+|www\S+|https\S+', '', text, flags=re.MULTILINE)
    
    # 2. Remove Punctuations and Special Characters (including Urdu ones)
    # This keeps Urdu letters and numbers but removes symbols like ! @ # ? ۔ ،
    text = re.sub(r'[^\w\s]', '', text)
    
    # 3. Tokenization
    words = text.split()
    
    # 4. Filter out stop words
    cleaned_words = [w for w in words if w not in URDU_STOP_WORDS]
    
    return " ".join(cleaned_words)